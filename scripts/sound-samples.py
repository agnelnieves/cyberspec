#!/usr/bin/env python3
"""Extract the supplied UI recordings into a portable registry module.

Requires ffmpeg. Originals are opened read-only; no source recordings are copied.
Usage: python3 scripts/sound-samples.py <ticking.mp3> <moving-slider.wav> <on-off.mp3> <motion.mp3> <press.mp3>
"""

import array
import base64
import hashlib
import json
from pathlib import Path
import subprocess
import sys

RATE = 48000


def decode(path):
    raw = subprocess.check_output([
        "ffmpeg", "-v", "error", "-i", str(path), "-f", "s16le",
        "-acodec", "pcm_s16le", "-ac", "1", "-ar", str(RATE), "-",
    ])
    samples = array.array("h", raw)
    if sys.byteorder != "little":
        samples.byteswap()
    return samples


def extract(samples, start, end, duration=None):
    clip = samples[round(start * RATE):round(end * RATE)]
    if duration is not None:
        # Time-compress the selected cue without shifting pitch. Keep each
        # atempo stage <=2 so large reductions don't simply skip samples.
        tempo = len(clip) / RATE / duration
        stages = []
        while tempo > 2:
            stages.append("atempo=2")
            tempo /= 2
        stages += [f"atempo={tempo:.12f}", "apad", f"atrim=duration={duration}"]
        if sys.byteorder != "little":
            clip.byteswap()
        raw = subprocess.check_output([
            "ffmpeg", "-v", "error", "-f", "s16le", "-ar", str(RATE), "-ac", "1",
            "-i", "pipe:0", "-af", ",".join(stages), "-f", "s16le", "-",
        ], input=clip.tobytes())
        clip = array.array("h", raw)
        if sys.byteorder != "little":
            clip.byteswap()
    # Retain the waveform/pitch; normalize headroom so engine gains are useful.
    level = 0.8 * 32767 / max(abs(value) for value in clip)
    fade = round(0.0005 * RATE)
    for i, value in enumerate(clip):
        envelope = min(1, i / fade, (len(clip) - 1 - i) / fade)
        clip[i] = round(value * level * envelope)
    if sys.byteorder != "little":
        clip.byteswap()
    return base64.b64encode(clip.tobytes()).decode("ascii")


tick_path, direction_path, toggle_path, motion_path, press_path = map(Path, sys.argv[1:])
tick, direction, toggle = decode(tick_path), decode(direction_path), decode(toggle_path)
motion, press = decode(motion_path), decode(press_path)
# The opening tick is partial. The following complete tick has its own quiet
# lead/tail; the adjustment loop spans eight complete periods (~69.815 ms each).
# The WAV has earlier bursts near 49 and 209 ms, then the different one at 368 ms.
cuts = {
    "hover": (tick, 0.037, 0.1068125),
    "adjust": (tick, 0.037, 0.5955208333333333),
    "decrement": (direction, 0.045, 0.135),
    "increment": (direction, 0.364, 0.459),
    # First and last variations, including their decay; discard the middle
    # variation at 1.38–2.59 seconds entirely.
    "on": (toggle, 0.004, 1.12),
    "off": (toggle, 2.910, 3.92),
    # The same fourth motion cue, compressed to the actual visual travel.
    # Dialog CSS is 280/150ms; drawer travel is perceptually complete well
    # before its ~500ms spring settles. sound.ts reverses each closing base.
    "modalOpen": (motion, 7.390, 8.900, 0.280),
    "modalCloseBase": (motion, 7.390, 8.900, 0.150),
    "drawerOpen": (motion, 7.390, 8.900, 0.350),
    "drawerCloseBase": (motion, 7.390, 8.900, 0.240),
    "drawerCloseShortBase": (motion, 7.390, 8.900, 0.180),
    # The cue around second 2 begins at 1.81s. Keep its complete attack.
    "press": (press, 1.808, 2.590),
}
lines = [
    "// Generated by scripts/sound-samples.py from the supplied recordings.",
    "// Recorded PCM is excluded from CyberSpec's MIT code license.",
    "// See https://github.com/agnelnieves/cyberspec/blob/main/THIRD_PARTY_NOTICES.md",
    "// Mono PCM16LE at 48 kHz, embedded so shadcn installs need no asset host.",
    "// 0.5 ms edge fades; normalized headroom, with playback gain in sound.ts.",
    f"// ticking.mp3 SHA256: {hashlib.sha256(tick_path.read_bytes()).hexdigest()}",
    f"// moving-slider-to-left.wav SHA256: {hashlib.sha256(direction_path.read_bytes()).hexdigest()}",
    f"// {toggle_path.name} SHA256: {hashlib.sha256(toggle_path.read_bytes()).hexdigest()}",
    f"// {motion_path.name} SHA256: {hashlib.sha256(motion_path.read_bytes()).hexdigest()}",
    f"// {press_path.name} SHA256: {hashlib.sha256(press_path.read_bytes()).hexdigest()}",
    "const soundSamples = {",
]
for name, (samples, start, end, *timing) in cuts.items():
    lines += [
        f"  // Source slice {start:.9f}–{end:.9f} seconds.",
    ]
    if timing:
        lines.append(f"  // Pitch-preserving tempo compression to {timing[0] * 1000:.0f} ms.")
    lines.append(f"  {name}: {{ sampleRate: {RATE}, pcm: {json.dumps(extract(samples, start, end, *timing))} }},")
lines += ["} as const", "", "export { soundSamples }", ""]
target = Path(__file__).resolve().parents[1] / "registry/cyber/lib/sound-samples.ts"
target.write_text("\n".join(lines))
print(f"Wrote {target.name}: {target.stat().st_size:,} bytes")
